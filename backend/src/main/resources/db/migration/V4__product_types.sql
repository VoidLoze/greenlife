-- Product types: the second level of the catalog (category -> type), used by the catalog sub-filters.
-- Layout and SKU assignment are generated from TYPES in scripts/build_seed.py; a fresh database gets the same data
-- from the seed, so the data part only touches databases that already hold the seeded products.

create table product_types (
    id          bigserial primary key,
    category_id bigint       not null references categories (id) on delete cascade,
    slug        varchar(80)  not null unique,
    name_ru     varchar(150) not null,
    name_kk     varchar(150),
    sort_order  int          not null default 0,
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now()
);
create index product_types_category_idx on product_types (category_id, sort_order);

alter table products add column type_id bigint references product_types (id) on delete set null;
create index products_type_idx on products (type_id);

