export default function PrivacyPage() {
  const { t, lang } = useT()
  const { data: settings } = useSettings()
  useDocumentTitle(t.privacy)
  const sections = lang === 'kk' ? KK : RU
  const place = settings ? [settings.city, settings.address].filter(Boolean).join(', ') : ''

  return (
    <article className="panel panel-pad legal-page">
      <span className="eyebrow">Greenleaf</span>
      <h1>{t.privacy}</h1>
      <p className="muted">
        {lang === 'kk'
          ? 'Бұл бет Greenleaf дүкені сайтта тапсырыс беру және тіркелу кезінде алатын дербес деректерді қалай пайдаланатынын түсіндіреді (Қазақстан Республикасының «Дербес деректер және оларды қорғау туралы» Заңы).'
          : 'Эта страница объясняет, как магазин Greenleaf использует персональные данные, которые получает при заказе и регистрации на сайте (Закон Республики Казахстан «О персональных данных и их защите»).'}
      </p>
      {sections.map((section) => (
        <section key={section.title}>
          <h2>{section.title}</h2>
          <ul>
            {section.items.map((item) => (
              <li key={item}>{item}</li>
            ))}
          </ul>
        </section>
      ))}
      <section>
        <h2>{t.contacts}</h2>
        <ul>
          {place && <li>{place}</li>}
          {settings?.phone && (
            <li>
              <a href={`tel:${settings.phone.replace(/\s/g, '')}`}>{formatPhone(settings.phone)}</a>
            </li>
          )}
          {settings?.whatsapp && (
            <li>
              <a href={`https://wa.me/${settings.whatsapp.replace(/\D/g, '')}`} target="_blank" rel="noreferrer">
                WhatsApp
              </a>
            </li>
          )}
        </ul>
      </section>
    </article>
  )
}
