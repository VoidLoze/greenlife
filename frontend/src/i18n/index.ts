const dictionaries: Record<Lang, Dict> = { ru, kk }

interface LangState {
  lang: Lang
  setLang: (lang: Lang) => void
}

export const useLangStore = create<LangState>()(
  persist(
    (set) => ({
      lang: 'ru',
      setLang: (lang) => {
        document.documentElement.lang = lang
        set({ lang })
      },
    }),
    { name: 'gl-lang' },
  ),
)

export function useT() {
  const lang = useLangStore((s) => s.lang)
  const dict = dictionaries[lang]
  /** Picks the Kazakh value when available, otherwise falls back to Russian. */
  const pick = (ruValue: string | null | undefined, kkValue: string | null | undefined) =>
    (lang === 'kk' && kkValue ? kkValue : ruValue) ?? ''
  return { t: dict, lang, pick }
}
